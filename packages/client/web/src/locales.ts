/** Typed translator accepted by the server-shell components. */
export type WebTranslate = Translate<WebCopyKey>

/**
 * Translate the pre-plugin login page from browser language preference.
 * @returns a translator backed by the matching server-shell dictionary.
 */
export function browserTranslate(): WebTranslate {
  const language = typeof navigator === 'undefined' ? 'zh' : navigator.language.toLowerCase()
  const dictionary = language.startsWith('zh') ? zh : en
  return (key, params) => {
    const template = dictionary[key]
    if (params === undefined) return template
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match)
  }
}
